-- compat: compatible
CREATE TABLE pwikit_include_mirror (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wiki       text        NOT NULL,
    page       text        NOT NULL,
    remote_id  bigint,
    source     text        NOT NULL DEFAULT '',
    status     text        NOT NULL,
    problem    text        NOT NULL DEFAULT '',
    fetched_at timestamptz NOT NULL,
    UNIQUE (wiki, page)
);

CREATE TABLE pwikit_include_ref (
    site_id    bigint NOT NULL REFERENCES web_site (id) ON DELETE CASCADE,
    article_id bigint NOT NULL REFERENCES web_article (id) ON DELETE CASCADE,
    wiki       text   NOT NULL,
    page       text   NOT NULL,
    PRIMARY KEY (article_id, wiki, page)
);

CREATE INDEX pwikit_include_ref_target ON pwikit_include_ref (wiki, page);
CREATE INDEX pwikit_include_ref_site ON pwikit_include_ref (site_id);
