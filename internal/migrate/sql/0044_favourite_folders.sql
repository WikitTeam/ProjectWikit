-- compat: compatible
CREATE TABLE pwikit_favourite_folder (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL REFERENCES web_user (id) ON DELETE CASCADE,
    name       text        NOT NULL,
    public     boolean     NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL
);

CREATE INDEX pwikit_favourite_folder_user ON pwikit_favourite_folder (user_id);

CREATE TABLE pwikit_favourite_place (
    user_id    bigint NOT NULL REFERENCES web_user (id) ON DELETE CASCADE,
    article_id bigint NOT NULL REFERENCES web_article (id) ON DELETE CASCADE,
    folder_id  bigint NOT NULL REFERENCES pwikit_favourite_folder (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, article_id)
);

CREATE INDEX pwikit_favourite_place_folder ON pwikit_favourite_place (folder_id);
